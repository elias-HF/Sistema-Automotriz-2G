-- Estructura de las tablas de la base de datos

CREATE TABLE IF NOT EXISTS cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    dni VARCHAR(15) UNIQUE,
    telefono VARCHAR(20),
    correo VARCHAR(120),
    direccion VARCHAR(200),
    activo BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS vehiculo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR(10) NOT NULL UNIQUE,
    marca VARCHAR(60) NOT NULL,
    modelo VARCHAR(60) NOT NULL,
    anio INTEGER,
    color VARCHAR(40),
    cliente_id BIGINT NOT NULL,
    FOREIGN KEY (cliente_id) REFERENCES cliente(id)
);

CREATE TABLE IF NOT EXISTS mecanico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    especialidad VARCHAR(100),
    telefono VARCHAR(20),
    activo BOOLEAN DEFAULT TRUE
    );

CREATE TABLE IF NOT EXISTS servicio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(250),
    precio DECIMAL(10,2) NOT NULL,
    activo BOOLEAN DEFAULT TRUE
    );

CREATE TABLE IF NOT EXISTS repuesto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    descripcion VARCHAR(250),
    precio DECIMAL(10,2) NOT NULL,
    stock INTEGER DEFAULT 0,
    stock_minimo INTEGER DEFAULT 0,
    activo BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS cita (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora TIMESTAMP NOT NULL,
    motivo VARCHAR(250),
    estado VARCHAR(30) DEFAULT 'PENDIENTE',
    cliente_id BIGINT NOT NULL,
    vehiculo_id BIGINT NOT NULL,
    FOREIGN KEY (cliente_id) REFERENCES cliente(id),
    FOREIGN KEY (vehiculo_id) REFERENCES vehiculo(id)
);

CREATE TABLE IF NOT EXISTS orden_reparacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_ingreso TIMESTAMP NOT NULL,
    fecha_entrega TIMESTAMP,
    descripcion_problema VARCHAR(500),
    estado VARCHAR(30) DEFAULT 'PENDIENTE',
    costo_total DECIMAL(10,2) DEFAULT 0,
    vehiculo_id BIGINT NOT NULL,
    mecanico_id BIGINT,
    FOREIGN KEY (vehiculo_id) REFERENCES vehiculo(id),
    FOREIGN KEY (mecanico_id) REFERENCES mecanico(id)
);

CREATE TABLE IF NOT EXISTS diagnostico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(1000) NOT NULL,
    fecha TIMESTAMP NOT NULL,
    observaciones VARCHAR(500),
    orden_id BIGINT NOT NULL UNIQUE,
    FOREIGN KEY (orden_id) REFERENCES orden_reparacion(id)
);

CREATE TABLE IF NOT EXISTS detalle_servicio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id BIGINT NOT NULL,
    servicio_id BIGINT NOT NULL,
    cantidad INTEGER DEFAULT 1,
    precio_unitario DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (orden_id) REFERENCES orden_reparacion(id),
    FOREIGN KEY (servicio_id) REFERENCES servicio(id)
);

CREATE TABLE IF NOT EXISTS detalle_repuesto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id BIGINT NOT NULL,
    repuesto_id BIGINT NOT NULL,
    cantidad INTEGER NOT NULL,
    precio_unitario DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (orden_id) REFERENCES orden_reparacion(id),
    FOREIGN KEY (repuesto_id) REFERENCES repuesto(id)
);

CREATE TABLE IF NOT EXISTS pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_pago TIMESTAMP NOT NULL,
    monto DECIMAL(10,2) NOT NULL,
    metodo_pago VARCHAR(40),
    estado VARCHAR(30) DEFAULT 'PENDIENTE',
    orden_id BIGINT NOT NULL,
    FOREIGN KEY (orden_id) REFERENCES orden_reparacion(id)
);