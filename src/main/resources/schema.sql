-- Base de datos del sistema automotriz 2G: Este esquema define las tablas principales del negocio y sus relaciones.

CREATE TABLE IF NOT EXISTS cliente (
    id_cliente INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    telefono VARCHAR(9) NOT NULL,
    correo VARCHAR(100) UNIQUE NOT NULL,
    codigo VARCHAR(10) UNIQUE NOT NULL,
    dni VARCHAR(8) UNIQUE NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS empleado (
    id_empleado INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    correo VARCHAR(50) UNIQUE NOT NULL,
    codigo VARCHAR(10) UNIQUE NOT NULL,
    usuario VARCHAR(25) UNIQUE NOT NULL,
    contrasenia VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    rol VARCHAR(25) NOT NULL CHECK (rol IN ('ADMINISTRADOR','RECEPCIONISTA','ALMACEN','MECANICO'))
);

CREATE TABLE IF NOT EXISTS articulo (
    id_articulo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) UNIQUE NOT NULL,
    descripcion VARCHAR(200) NOT NULL,
    precio_por_defecto DECIMAL(10, 2) NOT NULL,
    stock DECIMAL(10, 2) NOT NULL,
    codigo VARCHAR(10) UNIQUE NOT NULL,
    stock_minimo DECIMAL(10, 2) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    unidad_medida VARCHAR(5) NOT NULL
);

CREATE TABLE IF NOT EXISTS servicio (
    id_servicio INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) UNIQUE NOT NULL,
    descripcion VARCHAR(200) NOT NULL,
    codigo VARCHAR(10) UNIQUE NOT NULL,
    precio_por_defecto DECIMAL(10, 2) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    categoria VARCHAR(25) NOT NULL CHECK (categoria IN ('MANTENIMIENTO','MOTOR','FRENOS Y SUSPENSION','ELECTRICIDAD','TRANSMISION','DIAGNOSTICO Y OTROS'))
);

CREATE TABLE IF NOT EXISTS vehiculo (
    id_vehiculo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_fabricacion INT NOT NULL,
    placa VARCHAR(10) NOT NULL UNIQUE,
    kilometros DECIMAL(10, 2) NOT NULL,
    codigo VARCHAR(10) NOT NULL UNIQUE,
    modelo VARCHAR(25) NOT NULL,
    marca VARCHAR(25) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    id_cliente INT NOT NULL,

    FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
);

CREATE TABLE IF NOT EXISTS cita (
    id_cita INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    motivo VARCHAR(200) NOT NULL,
    estado VARCHAR(25) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','CANCELADA','ATENDIDA')),
    codigo VARCHAR(10) UNIQUE NOT NULL,
    medio_contacto VARCHAR(25) NOT NULL CHECK (medio_contacto IN ('PRESENCIAL','WHATSAPP','FACEBOOK','TELEFONO')),
    id_cliente INT NOT NULL,
    id_vehiculo INT NOT NULL,

    FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente),
    FOREIGN KEY (id_vehiculo) REFERENCES vehiculo(id_vehiculo)
);

CREATE TABLE IF NOT EXISTS orden (
    id_orden INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora_ingreso TIMESTAMP NOT NULL,
    fecha_hora_salida TIMESTAMP NULL,
    diagnostico VARCHAR(200) NOT NULL,
    monto_total DECIMAL(10, 2) NOT NULL DEFAULT 0,
    codigo VARCHAR(10) UNIQUE NOT NULL,
    estado VARCHAR(25) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','FINALIZADA','CANCELADA')),
    id_cita INT NOT NULL UNIQUE,

    FOREIGN KEY (id_cita) REFERENCES cita(id_cita)
);

CREATE TABLE IF NOT EXISTS comprobante (
    id_comprobante INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(10) NOT NULL UNIQUE,
    tipo_comprobante VARCHAR(25) NOT NULL CHECK (tipo_comprobante IN ('BOLETA', 'FACTURA')),
    metodo_pago VARCHAR(25) NOT NULL CHECK (metodo_pago IN ('TARJETA_DE_CREDITO', 'YAPE', 'PLIN','TARJETA_DE_DEBITO','EFECTIVO')),
    estado_pago VARCHAR(25) NOT NULL CHECK (estado_pago IN ('PENDIENTE', 'PAGADO', 'CANCELADO')),
    fecha_hora_emision TIMESTAMP NOT NULL,
    pago DECIMAL(10, 2) NOT NULL,
    total DECIMAL(10, 2) NOT NULL,
    id_orden INT NOT NULL UNIQUE,

    FOREIGN KEY (id_orden) REFERENCES orden(id_orden)
);

CREATE TABLE IF NOT EXISTS detalle_orden (
    id_detalle INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(25) NOT NULL CHECK (tipo IN ('ARTICULO', 'SERVICIO')),
    nombre VARCHAR(100) NOT NULL,
    cantidad DECIMAL(10, 2) NOT NULL,
    precio_aplicado DECIMAL(10, 2) NOT NULL,
    subtotal DECIMAL(10, 2) NOT NULL,
    id_orden INT NOT NULL,
    id_servicio INT NULL,
    id_articulo INT NULL,

    CHECK ((tipo = 'ARTICULO' AND id_articulo IS NOT NULL AND id_servicio IS NULL) OR (tipo = 'SERVICIO' AND id_servicio IS NOT NULL AND id_articulo IS NULL)),

    FOREIGN KEY (id_orden) REFERENCES orden(id_orden),
    FOREIGN KEY (id_servicio) REFERENCES servicio(id_servicio),
    FOREIGN KEY (id_articulo) REFERENCES articulo(id_articulo)
);

CREATE TABLE IF NOT EXISTS orden_empleado (
    id_orden INT NOT NULL,
    id_empleado INT NOT NULL,

    PRIMARY KEY (id_orden, id_empleado),
    FOREIGN KEY (id_orden) REFERENCES orden(id_orden),
    FOREIGN KEY (id_empleado) REFERENCES empleado(id_empleado)
);