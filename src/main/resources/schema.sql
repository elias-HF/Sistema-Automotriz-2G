
CREATE TABLE IF NOT EXISTS marca (
    id_marca INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS cliente (
    id_cliente INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    telefono VARCHAR(9) NOT NULL,
    correo VARCHAR(100) UNIQUE NOT NULL,
    cod VARCHAR(15) UNIQUE NOT NULL,
    dni VARCHAR(8) UNIQUE NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS medio_contacto (
    id_contacto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS unidad_medida (
    id_unidad INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) UNIQUE NOT NULL,
    abreviatura VARCHAR(10) NOT NULL
);

CREATE TABLE IF NOT EXISTS categoria (
    id_categoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) UNIQUE NOT NULL,
    descripcion VARCHAR(200) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS rol (
    id_rol INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) UNIQUE NOT NULL,
    descripcion VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS modelo (
    id_modelo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE,
    id_marca INT NOT NULL,

    FOREIGN KEY (id_marca) REFERENCES marca(id_marca)
);

CREATE TABLE IF NOT EXISTS empleado (
    id_empleado INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    correo VARCHAR(100) UNIQUE NOT NULL,
    cod VARCHAR(15) UNIQUE NOT NULL,
    usuario VARCHAR(50) UNIQUE NOT NULL,
    contrasenia VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    id_rol INT NOT NULL,

    FOREIGN KEY (id_rol) REFERENCES rol(id_rol)
);

CREATE TABLE IF NOT EXISTS articulo (
    id_articulo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) UNIQUE NOT NULL,
    descripcion VARCHAR(200) NOT NULL,
    precio DECIMAL(10, 2) NOT NULL,
    stock DECIMAL(10, 2) NOT NULL,
    cod VARCHAR(15) UNIQUE NOT NULL,
    stock_min DECIMAL(10, 2) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    id_unidad INT NOT NULL,

    FOREIGN KEY (id_unidad) REFERENCES unidad_medida(id_unidad)
);

CREATE TABLE IF NOT EXISTS servicio (
    id_servicio INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) UNIQUE NOT NULL,
    descripcion VARCHAR(200) NOT NULL,
    cod VARCHAR(15) UNIQUE NOT NULL,
    precio DECIMAL(10, 2) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    id_categoria INT NOT NULL,

    FOREIGN KEY (id_categoria) REFERENCES categoria(id_categoria)
);

CREATE TABLE IF NOT EXISTS vehiculo (
    id_vehiculo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_fabricacion INT NOT NULL,
    kilometros DECIMAL(10, 2) NOT NULL,
    cod VARCHAR(15) NOT NULL UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    id_modelo INT NOT NULL,
    id_cliente INT NOT NULL,

    FOREIGN KEY (id_modelo) REFERENCES modelo(id_modelo),
    FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
);

CREATE TABLE IF NOT EXISTS cita (
    id_cita INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    motivo VARCHAR(200) NOT NULL,
    estado VARCHAR(50) NOT NULL DEFAULT 'PENDIENTE'
    CHECK (estado IN ('PENDIENTE','CONFIRMADA','CANCELADA','ATENDIDA')),
    cod VARCHAR(15) UNIQUE NOT NULL,
    id_cliente INT NOT NULL,
    id_contacto INT NOT NULL,
    id_vehiculo INT NOT NULL,

    FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente),
    FOREIGN KEY (id_contacto) REFERENCES medio_contacto(id_contacto),
    FOREIGN KEY (id_vehiculo) REFERENCES vehiculo(id_vehiculo)
);

CREATE TABLE IF NOT EXISTS orden_servicio (
    id_orden INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fechaHora_ingreso TIMESTAMP NOT NULL,
    fechaHora_salida TIMESTAMP,
    diagnostico VARCHAR(200) NOT NULL,
    monto_total DECIMAL(10, 2) NOT NULL DEFAULT 0,
    cod VARCHAR(15) UNIQUE NOT NULL,
    estado VARCHAR(50) NOT NULL DEFAULT 'APROBADA'
    CHECK (estado IN ('APROBADA','FINALIZADA','EN_PROCESO')),
    id_vehiculo INT NOT NULL,

    FOREIGN KEY (id_vehiculo) REFERENCES vehiculo(id_vehiculo)
);

CREATE TABLE IF NOT EXISTS detalle_orden_articulo (
    id_orden INT NOT NULL,
    id_articulo INT NOT NULL,
    cantidad DECIMAL(10, 2) NOT NULL,
    precio_apli DECIMAL(10, 2) NOT NULL,

    PRIMARY KEY (id_orden, id_articulo),
    FOREIGN KEY (id_orden) REFERENCES orden_servicio(id_orden),
    FOREIGN KEY (id_articulo) REFERENCES articulo(id_articulo)
);

CREATE TABLE IF NOT EXISTS detalle_orden_servicio (
    id_orden INT NOT NULL,
    id_servicio INT NOT NULL,
    precio_apli DECIMAL(10, 2) NOT NULL,

    PRIMARY KEY (id_orden, id_servicio),
    FOREIGN KEY (id_orden) REFERENCES orden_servicio(id_orden),
    FOREIGN KEY (id_servicio) REFERENCES servicio(id_servicio)
);

CREATE TABLE IF NOT EXISTS detalle_orden_empleado (
    id_orden INT NOT NULL,
    id_empleado INT NOT NULL,
    descripcion VARCHAR(200) NOT NULL,
    horas_traba DECIMAL(5, 2) NOT NULL,

    PRIMARY KEY (id_orden, id_empleado),
    FOREIGN KEY (id_orden) REFERENCES orden_servicio(id_orden),
    FOREIGN KEY (id_empleado) REFERENCES empleado(id_empleado)
);

CREATE TABLE IF NOT EXISTS comprobante_pago (
    id_comprobante INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fechaHora_emision TIMESTAMP NOT NULL,
    met_pago VARCHAR(50) NOT NULL DEFAULT 'EFECTIVO' CHECK (met_pago IN ('EFECTIVO','YAPE','TARJETA_DE_CREDITO','PLIN','TARJETA_DE_DEBITO')),
    cod VARCHAR(15) UNIQUE NOT NULL,
    tipo_comp VARCHAR(50) NOT NULL DEFAULT 'FACTURA'
    CHECK (tipo_comp IN ('FACTURA', 'BOLETA')),
    estado VARCHAR(50) NOT NULL DEFAULT 'PENDIENTE'
    CHECK (estado IN ('PENDIENTE', 'PAGADO', 'ANULADO')),
    id_orden INT NOT NULL,

    FOREIGN KEY (id_orden) REFERENCES orden_servicio(id_orden)
);

CREATE TABLE IF NOT EXISTS movimiento_almacen (
    id_movimiento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(50) NOT NULL DEFAULT 'SALIDA'
    CHECK (tipo IN ('SALIDA', 'ENTRADA', 'AJUSTE')),
    fecha DATE NOT NULL,
    cod VARCHAR(15) UNIQUE NOT NULL,
    motivo VARCHAR(200) NOT NULL,
    cantidad DECIMAL(10, 2) NOT NULL,
    id_orden INT,
    id_articulo INT NOT NULL,

    FOREIGN KEY (id_orden) REFERENCES orden_servicio(id_orden),
    FOREIGN KEY (id_articulo) REFERENCES articulo(id_articulo)
);